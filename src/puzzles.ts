export type Point = [number, number]
export type Cat = { id: string; tap: Point[]; reveal: Point[] }
export type Puzzle = {
  id: string; version: number; title: string; location: string
  image: string; width: number; height: number; cats: Cat[]
}

// Tap polygons add a little forgiveness; reveals follow the visible pencil silhouette.
function cat(id: string, reveal: Point[]): Cat {
  const center = reveal.reduce(([x, y], p) => [x + p[0] / reveal.length, y + p[1] / reveal.length], [0, 0])
  return { id, reveal, tap: reveal.map(([x, y]) => [x + Math.sign(x - center[0]) * 12, y + Math.sign(y - center[1]) * 12]) }
}

